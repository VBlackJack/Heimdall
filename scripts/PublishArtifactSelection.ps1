<#
.SYNOPSIS
    Decides which files of the installer directory a publish uploads as release assets.

.DESCRIPTION
    A publish globs the installer directory for files carrying the build number and
    uploads what it finds. The directory is also where the run writes what it GENERATES:
    the checksum list, which is a real asset and is named explicitly, and the release
    notes file `RELEASE_NOTES_v<build>.md`, which is not an asset at all - it is passed
    to `gh release create --notes-file` and becomes the body of the release page.

    Nothing goes wrong on a first publish, because the glob runs before the notes are
    written. The residue is what bites: publish the same build number a second time,
    from a working copy where the first run left its notes behind, and the glob now
    carries `RELEASE_NOTES_v<build>.md` into the asset list. The release page then shows
    its own body as a downloadable file.

    So the decision lives here rather than inline in Build.ps1: it is one rule, it has
    one test, and Build.ps1 and that test share the rule itself instead of sharing a
    copy of it.

    The rule refuses generated documents by extension. Markdown in the installer
    directory is always something a run produced, never something a user should
    download: assets are installers, archives and the checksum list.

.NOTES
