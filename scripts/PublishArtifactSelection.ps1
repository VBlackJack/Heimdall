    Licensed under the Apache License, Version 2.0
#>

#Requires -Version 5.1

param()

# Extensions that are never a release asset, whatever their name. Markdown in the
# installer directory is generated by the run itself.
$script:NonAssetExtensions = @('.md')

function Select-PublishArtifact {
    <#
    .SYNOPSIS
        Filters candidate files down to those a publish should upload.
    .PARAMETER Candidate
        The files found in the installer directory for this build number.
    .OUTPUTS
        The subset to upload, in the order given.
    #>
    param(
        [Parameter(Mandatory)] [AllowEmptyCollection()] [System.IO.FileInfo[]] $Candidate
    )

    $kept = @()
    foreach ($file in $Candidate) {
        if ($script:NonAssetExtensions -contains $file.Extension.ToLowerInvariant()) {
            continue
        }

        $kept += $file
    }

    return $kept
}
